public enum UnicodeWordClassification {
    public static let unicodeVersion = "17.0.0"

    /// 业务作用：默认词字符采用固定 Unicode 字母、标记、数字与下划线，不随系统分类库变化。
    /// 参数说明:
    /// - scalar: 原始 Unicode 标量值，不是 UTF-8 字节或半个 UTF-16 代理项。
    /// 返回：固定词字符为真；分隔符、非法标量和未分配码点为假，不归一化正文。
    public static func contains(_ scalar: UInt32) -> Bool {
        if scalar < 128 {
            return (48...57).contains(scalar) || (65...90).contains(scalar)
                || (97...122).contains(scalar) || scalar == 95
        }
        var lower = 0
        var upper = ranges.count
        while lower < upper {
            let middle = lower + (upper - lower) / 2
            let value = ranges[middle]
            if scalar < UInt32(value >> 32) {
                upper = middle
            }
            else if scalar > UInt32(truncatingIfNeeded: value) {
                lower = middle + 1
            }
            else {
                return true
            }
        }
        return false
    }

